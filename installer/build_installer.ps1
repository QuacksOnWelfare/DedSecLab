#Requires -Version 5.1
# DedSecLab installer builder
# Dist default: ..\DedSecLabAPP_Beta\DedSecLab (relative)
# Inno skips Hidden/System files: un-hide before ISCC, re-hide after.
# No SignTool / private certs here.

<#
.SYNOPSIS
  Build DedSecLab-Setup-<version>.exe with Inno Setup 6.

.DESCRIPTION
  - Un-hides the Hidden+System dist assets folder so Inno can pack them.
  - Writes version.inc and compiles DedSecLab.iss -> installer\Output\
  - The installer's [Code] re-hides assets at the destination after install.

.PARAMETER AppVersion
  Override version (e.g. 1.0.6). Default: 1.0.6 (or version.inc).
#>
[CmdletBinding()]
param(
    [string]$AppVersion = '1.0.6',
    [string]$DistDir
)

$ErrorActionPreference = 'Stop'
$InstallerDir = $PSScriptRoot
$SourceRoot   = Resolve-Path (Join-Path $InstallerDir '..')
$IssPath      = Join-Path $InstallerDir 'DedSecLab.iss'
$VersionInc   = Join-Path $InstallerDir 'version.inc'

if (-not $DistDir) {
    $DistDir = Join-Path $SourceRoot 'DedSecLabAPP_Beta\DedSecLab'
}

function Find-ISCC {
    $candidates = @(
        "${env:LocalAppData}\Programs\Inno Setup 6\ISCC.exe",
        "${env:ProgramFiles(x86)}\Inno Setup 6\ISCC.exe",
        "$env:ProgramFiles\Inno Setup 6\ISCC.exe"
    )
    foreach ($c in $candidates) {
        if ($c -and (Test-Path -LiteralPath $c)) { return $c }
    }
    $cmd = Get-Command ISCC.exe -ErrorAction SilentlyContinue
    if ($cmd) { return $cmd.Source }
    return $null
}

if ($AppVersion -notmatch '^\d+(\.\d+){1,3}$') {
    throw "Invalid AppVersion '$AppVersion' (expected like 1.0.6)."
}

$exe = Join-Path $DistDir 'DedSecLab.exe'
if (-not (Test-Path -LiteralPath $exe)) {
    throw "Missing $exe - build the app first."
}

$assets = Join-Path $DistDir 'assets'
if (-not (Test-Path -LiteralPath $assets)) {
    throw "Missing assets folder: $assets"
}

# Inno Setup skips Hidden+System files. Clear those attrs on the source dist
# so the packer can see assets (icons, flags, dsl_upd.bin). The installer's
# [Code] HideAssets re-applies them at the destination after install.
Write-Host "Clearing Hidden+System on source assets so Inno can pack them..."
cmd /c "attrib -h -s `"$assets`" /d" | Out-Null
Get-ChildItem -LiteralPath $assets -Recurse -Force -ErrorAction SilentlyContinue | ForEach-Object {
    try {
        $_.Attributes = $_.Attributes -band (-bnot [IO.FileAttributes]::Hidden) -band (-bnot [IO.FileAttributes]::System)
    } catch {}
}

@(
    '; Auto-generated by build_installer.ps1 - do not edit by hand.'
    '#ifndef AppVersion'
    "  #define AppVersion `"$AppVersion`""
    '#endif'
) | Set-Content -LiteralPath $VersionInc -Encoding ASCII

$iscc = Find-ISCC
if (-not $iscc) {
    Write-Host "Inno Setup compiler (ISCC.exe) was not found." -ForegroundColor Yellow
    Write-Host "Install with:  winget install --id JRSoftware.InnoSetup -e"
    exit 1
}

Write-Host "ISCC:      $iscc"
Write-Host "Version:   $AppVersion"
Write-Host "Dist:      $DistDir"
Write-Host "Script:    $IssPath"

$outDir = Join-Path $InstallerDir 'Output'
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

& $iscc /DAppVersion=$AppVersion $IssPath
if ($LASTEXITCODE -ne 0) {
    throw "ISCC failed with exit code $LASTEXITCODE"
}

$setup = Join-Path $outDir "DedSecLab-Setup-$AppVersion.exe"
if (-not (Test-Path -LiteralPath $setup)) {
    throw "Expected output missing: $setup"
}

# Re-hide source assets so the dist folder stays as-shipped for local testing.
Write-Host "Re-hiding source assets..."
cmd /c "attrib +h +s `"$assets`" /d" | Out-Null
$upd = Join-Path $assets 'dsl_upd.bin'
if (Test-Path -LiteralPath $upd) {
    cmd /c "attrib +h +s `"$upd`"" | Out-Null
}

Write-Host ""
Write-Host "OK  $setup" -ForegroundColor Green
Write-Host "Size: $([math]::Round((Get-Item $setup).Length / 1MB, 1)) MB"
